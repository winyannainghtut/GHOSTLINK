// realityTarget is the TLS 1.3 site REALITY borrows its handshake from.
func realityTarget(t *testing.T) int {
	t.Helper()
	key, _ := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	template := &x509.Certificate{SerialNumber: big.NewInt(1), Subject: pkix.Name{CommonName: "reality.test"}, DNSNames: []string{"reality.test"},
		NotBefore: time.Now().Add(-time.Hour), NotAfter: time.Now().Add(time.Hour)}
	der, err := x509.CreateCertificate(rand.Reader, template, template, &key.PublicKey, key)
	if err != nil {
		t.Fatal(err)
	}
	listener, err := tls.Listen("tcp4", "127.0.0.1:0", &tls.Config{MinVersion: tls.VersionTLS13,
		Certificates: []tls.Certificate{{Certificate: [][]byte{der}, PrivateKey: key}}})
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { listener.Close() })
	go http.Serve(listener, http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) { io.WriteString(w, "decoy site") }))
	return listener.Addr().(*net.TCPAddr).Port
}

func realityContext() context.Context {
	in := inbound.NewRegistry()
	mixed.RegisterInbound(in)
	vless.RegisterInbound(in)
	out := outbound.NewRegistry()
	vless.RegisterOutbound(out)
	direct.RegisterOutbound(out)
	dnsRegistry := dns.NewTransportRegistry()
	local.RegisterTransport(dnsRegistry)
	return box.Context(context.Background(), in, out, endpoint.NewRegistry(), dnsRegistry, boxservice.NewRegistry(), certificate.NewRegistry())
}

func startRealityBox(t *testing.T, config string) {
	t.Helper()
	ctx := realityContext()
	options, err := boxjson.UnmarshalExtendedContext[option.Options](ctx, []byte(config))
	if err != nil {
		t.Fatalf("parse: %v\n%s", err, config)
	}
	options.Log = &option.LogOptions{Disabled: true}
	instance, err := box.New(box.Options{Context: ctx, Options: options})
	if err != nil {
		t.Fatal(err)
	}
	if err := instance.Start(); err != nil {
		instance.Close()
		t.Fatal(err)
	}
	t.Cleanup(func() { instance.Close() })
}

func freeTCP(t *testing.T) int {
	listener, err := net.Listen("tcp4", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	defer listener.Close()
	return listener.Addr().(*net.TCPAddr).Port
}

// Mirrors the VLESS-Reality outbound generated by core/vpn-engine/src/worker_session.rs.
func TestVlessRealityCarriesTrafficAndRejectsWrongShortID(t *testing.T) {
	var private [32]byte
	rand.Read(private[:])
	public, _ := curve25519.X25519(private[:], curve25519.Basepoint)
	privateKey := base64.RawURLEncoding.EncodeToString(private[:])
	publicKey := base64.RawURLEncoding.EncodeToString(public)
	const id = "8f3d2c1b-1a2b-4c3d-9e8f-0123456789ab"
	target := realityTarget(t)
	web, err := net.Listen("tcp4", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	defer web.Close()
	go http.Serve(web, http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) { io.WriteString(w, "through vless reality") }))
	serverPort := freeTCP(t)
	startRealityBox(t, fmt.Sprintf(`{
	  "inbounds":[{"type":"vless","tag":"in","listen":"127.0.0.1","listen_port":%d,"users":[{"name":"alice","uuid":%q,"flow":"xtls-rprx-vision"}],
	    "tls":{"enabled":true,"server_name":"reality.test","reality":{"enabled":true,"handshake":{"server":"127.0.0.1","server_port":%d},"private_key":%q,"short_id":["0123abcd"]}}}],
	  "outbounds":[{"type":"direct","tag":"direct"}],"route":{"final":"direct"}
	}`, serverPort, id, target, privateKey))
	for _, tc := range []struct {
		shortID string
		works   bool
	}{{"0123abcd", true}, {"ffffffff", false}} {
		proxyPort := freeTCP(t)
		startRealityBox(t, fmt.Sprintf(`{
		  "inbounds":[{"type":"mixed","tag":"in","listen":"127.0.0.1","listen_port":%d}],
		  "outbounds":[{"type":"vless","tag":"proxy","server":"127.0.0.1","server_port":%d,"uuid":%q,"flow":"xtls-rprx-vision",
		    "tls":{"enabled":true,"server_name":"reality.test","utls":{"enabled":true,"fingerprint":"chrome"},"reality":{"enabled":true,"public_key":%q,"short_id":%q}}}],
		  "route":{"final":"proxy"}
		}`, proxyPort, serverPort, id, publicKey, tc.shortID))
		proxy, _ := url.Parse(fmt.Sprintf("http://127.0.0.1:%d", proxyPort))
		client := &http.Client{Transport: &http.Transport{Proxy: http.ProxyURL(proxy), DisableKeepAlives: true}, Timeout: 5 * time.Second}
		response, err := client.Get("http://" + web.Addr().String() + "/")
		body := ""
		if err == nil {
			raw, _ := io.ReadAll(response.Body)
			response.Body.Close()
			body = string(raw)
		}
		if tc.works && body != "through vless reality" {
			t.Fatalf("REALITY client could not connect: body=%q err=%v", body, err)
		}
		if !tc.works && body == "through vless reality" {
			t.Fatal("a client with the wrong short ID was accepted")
		}
	}
}
